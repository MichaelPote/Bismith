// Regenerate src/presets/builtin.ts: a static import of every preset file in presets/ (docs/features/fr5.4-presets.md),
// so the app, the tests and tsx tools all load them the same way.
//
//   npx tsx tools/presets-index.ts
//
// Run it after adding, renaming or removing a file in presets/; tools/previews.ts runs it too, and presets.test.ts fails
// while the index and the folder disagree.

import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const PRESET_DIR = join(ROOT, 'presets');

/** Every preset file, as its path under presets/ without `.json` ("project/bricks", "layer/bricks/red-brick"). */
export function presetFiles(dir = PRESET_DIR): string[] {
	const out: string[] = [];
	const walk = (d: string) => {
		for (const name of readdirSync(d).sort()) {
			const p = join(d, name);
			if (statSync(p).isDirectory()) walk(p);
			else if (name.endsWith('.json')) out.push(relative(PRESET_DIR, p).replace(/\\/g, '/').slice(0, -5));
		}
	};
	walk(dir);
	return out;
}

export function writePresetIndex(): number {
	const keys = presetFiles();
	const lines = keys.map((k, i) => `import f${i} from '../../presets/${k}.json';`);
	const body = keys.map((k, i) => `\t${JSON.stringify(k)}: f${i},`).join('\n');
	writeFileSync(
		join(ROOT, 'src/presets/builtin.ts'),
		`// Generated by tools/presets-index.ts: every preset file in presets/, by its path there without .json.
// Regenerate after adding, renaming or removing one (presets.test.ts checks).
${lines.join('\n')}

export const BUILTIN_FILES: Record<string, unknown> = {
${body}
};
`
	);
	return keys.length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	console.log(`wrote src/presets/builtin.ts (${writePresetIndex()} presets)`);
}
