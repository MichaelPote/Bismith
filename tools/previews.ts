// Render every example project (preset) and store a small preview of each in src/presets/previews.ts, so the new-project
// wizard shows them without compiling and rendering (docs/features/fr8.20-project-previews.md).
//
//   npx tsx tools/previews.ts [--backend windows|swiftshader] [--samples 64] [--only id1,id2]
//
// Run it after changing a preset (or the renderer, if the examples' look moved); presets.test.ts checks every preset has one.

import { writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { openSession, type BackendKind } from './backend'
import { PRESETS } from '../src/presets'
import { PRESET_PREVIEWS } from '../src/presets/previews'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const flag = (n: string, d?: string) => {
  const i = args.indexOf(`--${n}`)
  return i >= 0 ? args[i + 1] : d
}
const samples = Number(flag('samples', '64'))
const only = (flag('only', '') ?? '').split(',').filter(Boolean)

async function main() {
  const s = await openSession({ backend: flag('backend') as BackendKind | undefined, workers: 1, logPage: false })
  console.log(`[previews] ${s.backend}: ${s.renderer}`)
  const out: Record<string, string> = { ...PRESET_PREVIEWS }
  try {
    for (const p of PRESETS) {
      if (only.length && !only.includes(p.id)) continue
      await s.callOn(0, 'loadProject', { ...p.build(), preview: undefined })
      await s.callOn(0, 'render', { samples })
      const url = await s.callOn<string | undefined>(0, 'preview')
      if (!url) throw new Error(`${p.id}: no preview`)
      out[p.id] = url
      console.log(`${p.id.padEnd(10)} ${(url.length / 1024).toFixed(1)} KB  ${url.slice(5, url.indexOf(';'))}`)
    }
  } finally {
    await s.close()
  }
  const ids = PRESETS.map((p) => p.id).filter((id) => out[id])
  const body = ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(out[id])},`).join('\n')
  writeFileSync(
    join(ROOT, 'src/presets/previews.ts'),
    `// Generated by tools/previews.ts: a small preview of each example project for the new-project wizard (FR8.20), so it
// shows them without compiling and rendering. Regenerate after changing a preset or the renderer.
export const PRESET_PREVIEWS: Record<string, string> = {
${body}
}
`,
  )
  console.log(`wrote src/presets/previews.ts (${ids.length} previews, ${(body.length / 1024).toFixed(1)} KB)`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
